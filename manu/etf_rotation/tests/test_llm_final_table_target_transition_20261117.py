"""🔴 2026-11-17 新增：**目标列「过渡写法」（箭头）必须取落点**的回归测试。

【真机事故（交付件 `snapshots/20261117_221846`）】
「最终交易决定」章的**裁决表**里，512800 的目标列写的是**过渡**：

    | 512800 银行ETF华宝 | **减** | 22.54% → **约12%**（硬上限16%），按0.874约从7,700股减至约4,100股… |

⇒ 旧口径的**转变标记表**只认「降至 / 减至 / 调到 …」等**词**，
   **不认箭头**「→」⇒ 目标列取**第一个**百分数（= **起点** 22.54%）
⇒ 计划把 512800 记成「TA 目标 **22.5%**」（= 当前权重，等于说"不用减"）
⇒ ① 闸门 A20③「最终裁决必须**可回放**」判红
   （原文里根本没有独立的「22.5」这个数，只有「22.54%」）
   ② 交付面「TA 目标」与裁决原文（**减至约 12%**）**自相矛盾**。

【修法】`llm_final._TABLE_TRANSITION_RE`：把箭头形态（→ / -> / ⇒ / ⟶ / —>）
   也认作**转变标记** ⇒ 取箭头**之后**那个百分数（= 落点）⇒ 12%。
"""

from __future__ import annotations

import re

import llm_final as LLF


#: 真机原文（裁决表 · 512800 行 · 目标列）
_CELL_512800 = (
    "22.54% → **约12%**（硬上限16%），按0.874约从7,700股减至约4,100股"
    "（卖出约3,600股/约3,150元，比机械方案多减）"
)


def test_真机_箭头过渡目标取落点而不是起点() -> None:
    """「22.54% → 约12%」⇒ 目标必须是 **12%**（落点），不是 22.54%（起点）。"""
    pct = LLF._table_target_pct(_CELL_512800)
    assert pct == 12.0, f"过渡目标必须取箭头之后的落点 12%（实测 {pct}）"


def test_变异反证_箭头移出转变标记表后必须变红() -> None:
    """把箭头从转变标记表里去掉 ⇒ 上一条必须变红（证明这层护栏真在承重）。"""
    saved = LLF._TABLE_TRANSITION_RE
    try:
        LLF._TABLE_TRANSITION_RE = re.compile(
            r"(?:降至|减至|降到|调至|下调至|下调到|压缩至|压缩到|调整至|调整到)")
        pct = LLF._table_target_pct(_CELL_512800)
        assert pct != 12.0, f"变异后应当取回起点（证明护栏承重），实测 {pct}"
    finally:
        LLF._TABLE_TRANSITION_RE = saved


def test_词形过渡口径不变() -> None:
    """既有口径「从 20% 降至 10%」⇒ 10%（不许被本次改动带坏）。"""
    assert LLF._table_target_pct("从 20% 降至 10%") == 10.0
    assert LLF._table_target_pct("**约11%**（标准槽位）") == 11.0
    assert LLF._table_target_pct("**约5%**，仅当12/1重跑后仍站上MA60") == 5.0


def test_箭头后没有百分数时不得编造() -> None:
    """「80% → 按等权口径」（箭头后无数字）⇒ 抽不出就返回 None（不许编造）。"""
    val = LLF._table_target_pct("80% → 按等权口径")
    assert val is not None and val == 80.0, f"回落口径（实测 {val}）"
