#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""🛡️ 一票否决的**代码归属**：比较对象 / 比分引述**不得**被当成否决主体。

【钉的是什么】（2026-11-13 全量跑批 `snapshots/20261113_092926` 实证）
① **比较对象**误判：真机研究经理结论段原句
     「- 563020（红利低波ETF易方达）：若出现在顺延池即否决
       （与 515450 同族、相关性 0.919、分位 86% 拥挤、最终分 +0.0370 **弱于 515450**）」
   ⇒ 真机**同时**写明「**515450 仅条件性买入**」「| 515450 | **买** |」
   ⇒ 旧口径把 515450 当成否决主体（`_REJECT_WINDOW=40` 把它拉进动词作用域）
      ⇒ **TA 要买的那只被剔出候选** ⇒ 席位被顺延给别的标的。
② **比分引述**误判：同一段
     「……（医药类 512170 -1.3950、512010 -1.4778，且两者互为同族只能选一只），
       否决它等于用 -1.4 分的资产换 -0.0852 分的资产」
   ⇒ 512010 只是**比分引述**，被**跨子句继承**成「否决它」的主体
      ⇒ 一只没被点名否决的标的被写进「TA 一票否决」名单。

【口径】
* 比较对象（「与 X 同族」「弱于 X」）⇒ **引用**，不作否决主体；
* 比分引述（「代码 + 带符号小数」）⇒ **只禁跨子句继承**（子句内判定口径一字未动）；
* 真机**点名否决**的标的**必须仍然被抓到**（不许因为修 bug 而漏放）。

【本测试怎么保证有牙】
每个修复都配一个**运行时变异反证**：把对应护栏改废 ⇒ 对应断言**必须转红**
（= 证明「若无此护栏，真机件就会误判」，而不是「断言本来就不成立」）。
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import llm_final as L  # noqa: E402

#: 🔴 真机原句（研究经理结论段，**逐字**取自 `snapshots/20261113_092926`）
REAL_LINE = (
    "- 563020（红利低波ETF易方达）：若出现在顺延池即否决"
    "（与 515450 同族、相关性 0.919、分位 86% 拥挤、最终分 +0.0370 弱于 515450）"
)
#: 真机同段的**比分引述 + 跨子句继承**原句
REAL_SCORE_LINE = (
    "第二，拥挤度是风险提示而不是选股依据，只可作否决的补充理由——"
    "正因如此我拒绝熊方对 515650 的否决：515650 的 E=+0.3401 是全部非银行候选里最高的，"
    "最终分 -0.0852 也远好于顺延替代品（医药类 512170 -1.3950、512010 -1.4778，"
    "且两者互为同族只能选一只），否决它等于用 -1.4 分的资产换 -0.0852 分的资产，是自伤"
)


def _codes(text: str) -> set[str]:
    return {r["code"] for r in L.extract_rejections(text)}


# ---------------------------------------------------------------- ① 比较对象
def test_真机原句_比较对象515450不得被当成否决主体() -> None:
    """🔴 主用例：与 515450 同族 / 弱于 515450 ⇒ 515450 不是否决主体。"""
    codes = _codes(REAL_LINE)
    assert "515450" not in codes, f"🔴 比较对象被误判成否决：{codes}"
    assert "563020" in codes, f"主语 563020 必须仍被点名否决：{codes}"


def test_比较引用护栏_必须逐条命中真机原句() -> None:
    """🔴 **逐条承重**：真机原句里的**两处**比较引用必须**各自**被对应护栏命中。

    ⇒ 「与 515450 同族」由 `_MD_REF_COMPARE_RE` 命中；
    ⇒ 「弱于 515450」由 `_MD_REF_SUPERIOR_RE` 命中。
    ⇒ 两条护栏**各自**承重（不是「有一条在兜底就行」）。
    """
    assert "515450" in {m.group("code") for m in L._MD_REF_COMPARE_RE.finditer(REAL_LINE)}
    assert "515450" in {m.group("code") for m in L._MD_REF_SUPERIOR_RE.finditer(REAL_LINE)}


def test_变异_同时废掉两条比较护栏_515450必须重新被误判(monkeypatch) -> None:
    """🔴 **变异反证**：把两条比较引用护栏一起废掉（= 修复前的状态）
    ⇒ 515450 必须重新被误判 ⇒ 证明「若无此护栏，真机件确实会误伤 TA 要买的那只」。
    """
    monkeypatch.setattr(
        L, "_MD_REF_COMPARE_RE",
        re.compile(
            r"(?:与|和|跟|相比|对比|较之|之于)\s*(?P<code>[1-9]\d{5})"
            r"\s*(?:的)?\s*(?:相关性|相关度|相关系数|重叠度|重合度|重叠|重合|相似度|重复度|替代性)"
        ),
    )
    monkeypatch.setattr(L, "_MD_REF_SUPERIOR_RE", re.compile(r"(?!x)x"))
    codes = _codes(REAL_LINE)
    assert "515450" in codes, "变异后必须重新误判 515450（否则本用例是假通过）"


# ---------------------------------------------------------------- ② 比分引述
def test_真机原句_比分引述512010不得被跨子句继承成否决() -> None:
    """🔴 主用例：512170 -1.3950、512010 -1.4778 是比分引述 ⇒ 512010 不是否决主体。"""
    codes = _codes(REAL_SCORE_LINE)
    assert "512010" not in codes, f"🔴 比分引述被误判成否决：{codes}"


def test_真机原句_去掉比分引述护栏_512010必须重新被误判(monkeypatch) -> None:
    """🔴 **变异反证**：废掉「代码 + 带符号小数」护栏 ⇒ 512010 必须重新被误判。"""
    monkeypatch.setattr(L, "_MD_DATA_CITATION_RE", re.compile(r"(?!x)x"))
    codes = _codes(REAL_SCORE_LINE)
    assert "512010" in codes, "变异后必须重新误判 512010（否则本用例是假通过）"


# ---------------------------------------------------------------- ③ 不许漏放
def test_点名否决必须仍然被抓到_不得因修bug而漏放() -> None:
    """🔴 **反向负例**：真正**点名否决**的标的必须仍然被抓到（不许修 bug 修成漏放）。"""
    assert "512170" in _codes("正式否决 512170，不建仓"), "点名否决漏放"
    assert "515650" in _codes("- 515650（消费50ETF富国）：否决"), "点名否决漏放"
    assert "563020" in _codes("563020 正式一票否决，移出顺延池"), "点名否决漏放"


def test_条件句与买入意图仍不判否决() -> None:
    """🔴 **反向负例**：既有护栏不得被本次改动带坏。"""
    assert "512800" not in _codes("512800 若不满足持有条件，则剔除 512800"), "条件句误伤"
    assert "515450" not in _codes("515450 条件性买入"), "买入意图误伤"


def test_真机整段_比较对象与比分引述不得进名单() -> None:
    """🔴 **真机整段回归**：把真机那段话整段喂进去
    ⇒ 515450（比较对象）/ 512010（比分引述）都不在名单；563020（点名否决）必须在。

    🔴 2026-11-13 语义修正：本段里的 515650 **不是**被否决 —— 研究经理在这段里
       **驳回**熊方对 515650 的否决（并主张买入它）⇒ 这一段**不得**产出对 515650 的否决。
       515650 的**真否决**来自风险裁决 / 最终交易决定 ⇒ 见 `test_真机最终裁决段_515650必须仍被否决`。
    """
    codes = _codes(REAL_SCORE_LINE + "\n\n" + REAL_LINE)
    assert "515450" not in codes, f"🔴 比较对象被误判：{codes}"
    assert "512010" not in codes, f"🔴 比分引述被误判：{codes}"
    assert "515650" not in codes, f"🔴 驳回否决的元结构被误判成否决：{codes}"
    assert "563020" in codes, f"点名否决漏放：{codes}"


def test_真机最终裁决段_515650必须仍被否决() -> None:
    """🔴 **成对负例**：真机**风险裁决 / 最终交易决定**段对 515650 的**真否决**
    ⇒ 必须仍然被抓到（不许因为修「驳回否决」护栏而漏放真否决）。

    原句（逐字取自 `snapshots/20261113_092926` 的 `## 六、最终交易决定（原始输出）`）：
        「515650（消费50ETF富国）：按保守派与中性派的多数意见维持否决——最终分 -0.0852…」
    """
    codes = _codes(
        "515650（消费50ETF富国）：按保守派与中性派的多数意见维持否决"
        "——最终分 -0.0852、放量 1.81 / 分位 93% 已触发拥挤补充否决条件，不另设 16% 卫星仓。"
    )
    assert "515650" in codes, f"🔴 真否决漏放：{codes}"
