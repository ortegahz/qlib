#: 旧口径（2026-11-16 之前）：否定前缀必须**贴脸**裸动词。
_OLD_NEG_PREFIX_RE = re.compile(
    r"(?<!得)(?<!未尝)(?<!无)"
    r"(?:尚未|从未|不再|不予|不得|不可|不能|不应|无需|无须|避免|禁止|杜绝|并非|不|未)"
    r"[\s*`_~]*(?:正式|再|会|予以|进行|做|作|考虑|准备|打算)?[\s*`_~]*"
    r"(?P<verb>否决|剔除|排除|移除|回避|暂缓|放弃)"
)


def test_变异反例_回退分支二_必须转红():
    """把分支②回退成旧口径 ⇒ ① 必须转红 ⇒ 证明本测试**有牙**。"""
    original = LLF._REJECT_NEG_PREFIX_RE
    try:
        LLF._REJECT_NEG_PREFIX_RE = _OLD_NEG_PREFIX_RE
        codes = _codes(_MD_RESEARCH_MANAGER)
        assert "512800" in codes, "变异后仍未命中 ⇒ 这条断言没有牙"
    finally:
        LLF._REJECT_NEG_PREFIX_RE = original
    assert "512800" not in _codes(_MD_RESEARCH_MANAGER)
